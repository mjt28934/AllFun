package app.allfun.data

import app.allfun.data.backup.BackupFile
import app.allfun.data.backup.BackupMedia
import app.allfun.data.backup.BackupSettings
import app.allfun.data.update.ReleaseInfo
import kotlinx.serialization.Serializable
import kotlinx.serialization.builtins.ListSerializer
import kotlinx.serialization.builtins.serializer
import kotlinx.serialization.encodeToString
import kotlinx.serialization.json.Json
import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertTrue
import org.junit.Test
import java.lang.reflect.Modifier

/**
 * Guards the runtime property that broke modern Tachiyomi/Mihon extensions.
 *
 * Extensions ship their own generated serializers compiled against whatever
 * kotlinx-serialization the extension library used. When the host's serialization runtime is
 * older than the extension's compiler, the generated serializer can omit members that older
 * interfaces declared abstract, and every descriptor lookup throws `AbstractMethodError`.
 *
 * `GeneratedSerializer.typeParametersSerializers()` is that member: abstract in 1.7.x,
 * a real JVM default method from 1.8.0 on. These tests fail if the host ever ships a version
 * where a serializer generated by a current compiler cannot be instantiated, and they also
 * exercise the generic/polymorphic/defaults paths extensions rely on.
 */
class SerializationCompatibilityTest {

    private val json = Json { ignoreUnknownKeys = true }

    @Serializable
    data class Box<T>(val value: T, val items: List<T> = emptyList())

    @Serializable
    sealed class Shape {
        @Serializable
        data class Circle(val radius: Double) : Shape()

        @Serializable
        data class Square(val side: Double) : Shape()
    }

    @Test
    fun `type parameters serializer hook is a default method not an abstract one`() {
        // Reflection on the bytecode rather than the Kotlin API: extensions link against the
        // JVM interface, and a generated serializer that omits this method is fine only if
        // the interface supplies an implementation.
        val generated = Class.forName("kotlinx.serialization.internal.GeneratedSerializer")
        val hook = generated.getMethod("typeParametersSerializers")

        assertFalse(
            "typeParametersSerializers() must not be abstract or newer extensions crash with " +
                "AbstractMethodError; bump kotlinx-serialization to 1.8.0 or newer",
            Modifier.isAbstract(hook.modifiers)
        )
        assertTrue(
            "typeParametersSerializers() must be a real default method on the interface",
            hook.isDefault
        )
    }

    @Test
    fun `generic serializers generate and round trip`() {
        val value = Box("solo", listOf("a", "b"))
        val encoded = json.encodeToString(Box.serializer(String.serializer()), value)
        val decoded = json.decodeFromString(Box.serializer(String.serializer()), encoded)

        assertEquals(value, decoded)
        // The list serializer exercises the generic child-serializer path.
        assertEquals(2, json.decodeFromString(ListSerializer(String.serializer()), """["x","y"]""").size)
    }

    @Test
    fun `polymorphic serializers keep their concrete type`() {
        val shapes: List<Shape> = listOf(Shape.Circle(1.5), Shape.Square(2.0))
        val encoded = json.encodeToString(ListSerializer(Shape.serializer()), shapes)
        val decoded = json.decodeFromString(ListSerializer(Shape.serializer()), encoded)

        assertEquals(shapes, decoded)
        assertTrue(decoded[0] is Shape.Circle)
        assertTrue(decoded[1] is Shape.Square)
    }

    @Test
    fun `missing fields fall back to defaults and unknown fields are ignored`() {
        val decoded = json.decodeFromString(Box.serializer(String.serializer()), """{"value":"v"}""")
        assertEquals(Box("v", emptyList()), decoded)

        val withExtra = json.decodeFromString(
            Box.serializer(String.serializer()),
            """{"value":"v","items":["i"],"futureField":42}"""
        )
        assertEquals(Box("v", listOf("i")), withExtra)
    }

    @Test
    fun `backup file round trips through the app's own model`() {
        val backup = BackupFile(
            appVersion = "0.8.0",
            createdAt = 1_700_000_000_000L,
            settings = BackupSettings(novelFontSize = 120, reduceMotion = true),
            media = listOf(
                BackupMedia(
                    id = "m1",
                    kind = "MANGA",
                    sourceId = "komikku:123",
                    sourceKey = "k1",
                    title = "Solo Leveling",
                    genres = "Action,Manhwa",
                    inLibrary = true
                )
            )
        )

        val decoded = Json.decodeFromString(BackupFile.serializer(), Json.encodeToString(backup))

        assertEquals("0.8.0", decoded.appVersion)
        assertEquals(120, decoded.settings?.novelFontSize)
        assertEquals("Solo Leveling", decoded.media.single().title)
        assertEquals(backup, decoded)
    }

    @Test
    fun `release info deserializes when optional checksum fields are absent`() {
        val raw = """
            {
              "tag": "v0.8.0",
              "versionName": "0.8.0",
              "title": "AllFun 0.8.0",
              "notes": "notes",
              "publishedAt": "2026-11-19T00:00:00Z",
              "apkAssetName": "AllFun-0.8.0-release.apk",
              "apkUrl": "https://example.test/apk",
              "apkSize": 1234,
              "releaseUrl": "https://example.test/release"
            }
        """.trimIndent()

        val release = Json.decodeFromString(ReleaseInfo.serializer(), raw)

        assertEquals("v0.8.0", release.tag)
        assertEquals(1234L, release.apkSize)
        assertEquals(null, release.checksumSha256)
    }
}
